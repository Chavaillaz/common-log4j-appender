package com.chavaillaz.appender.log4j;

import java.time.Duration;

import lombok.Value;
import org.apache.logging.log4j.Level;
import org.jspecify.annotations.Nullable;

import com.chavaillaz.appender.DeliveryOptions;
import com.chavaillaz.appender.LogConfiguration;

/**
 * Minimal, real, immutable implementation of {@link LogConfiguration} used across the test suite instead
 * of mocking the interface, to keep tests closer to actual usage and avoid repeating stubbing boilerplate.
 * <p>
 * Its builder deliberately keeps a flat setter per {@link DeliveryOptions} knob, rather than taking a
 * pre-built instance: a test tuning one setting reads better as {@code builder().flushThreshold(2).build()}
 * than as the nested equivalent, and the tests care about the setting, not about where it lives.
 */
@Value
class TestLogConfiguration implements LogConfiguration {

    String application;
    String host;
    String environment;
    DeliveryOptions deliveryOptions;

    static Builder builder() {
        return new Builder();
    }

    /**
     * Hand-written rather than generated by Lombok, so the flat setters below can feed a nested
     * {@link DeliveryOptions.Builder} while the built configuration still only holds the record.
     */
    static final class Builder {

        private String application = "test-application";
        private String host = "test-host";
        private String environment = "test-environment";

        private final DeliveryOptions.Builder options = DeliveryOptions.builder()
                .flushThreshold(10)
                .flushInterval(Duration.ofSeconds(5))
                // Backing off is deliberately disabled by default here, unlike DeliveryOptions' own
                // production default: most tests drive retries by calling flush() in a loop and asserting on
                // the outcome right after, which a real delay would turn into either a sleep or a flaky wait.
                // Tests specifically covering the backoff set it explicitly instead.
                .retryBackoff(Duration.ZERO)
                .maxRetryBackoff(Duration.ZERO)
                .closeTimeout(Duration.ofSeconds(10));

        Builder application(String application) {
            this.application = application;
            return this;
        }

        Builder host(String host) {
            this.host = host;
            return this;
        }

        Builder environment(String environment) {
            this.environment = environment;
            return this;
        }

        Builder flushThreshold(long flushThreshold) {
            options.flushThreshold(flushThreshold);
            return this;
        }

        Builder flushInterval(Duration flushInterval) {
            options.flushInterval(flushInterval);
            return this;
        }

        Builder flushLevel(@Nullable Level flushLevel) {
            options.flushLevel(flushLevel);
            return this;
        }

        Builder maxConcurrentTransmissions(int maxConcurrentTransmissions) {
            options.maxConcurrentTransmissions(maxConcurrentTransmissions);
            return this;
        }

        Builder maxPendingDocuments(int maxPendingDocuments) {
            options.maxPendingDocuments(maxPendingDocuments);
            return this;
        }

        Builder maxRequestDocuments(int maxRequestDocuments) {
            options.maxRequestDocuments(maxRequestDocuments);
            return this;
        }

        Builder maxPendingBytes(long maxPendingBytes) {
            options.maxPendingBytes(maxPendingBytes);
            return this;
        }

        Builder maxRequestBytes(long maxRequestBytes) {
            options.maxRequestBytes(maxRequestBytes);
            return this;
        }

        Builder maxConsecutiveFailures(int maxConsecutiveFailures) {
            options.maxConsecutiveFailures(maxConsecutiveFailures);
            return this;
        }

        Builder maxQueuedEvents(int maxQueuedEvents) {
            options.maxQueuedEvents(maxQueuedEvents);
            return this;
        }

        Builder retryBackoff(Duration retryBackoff) {
            options.retryBackoff(retryBackoff);
            return this;
        }

        Builder maxRetryBackoff(Duration maxRetryBackoff) {
            options.maxRetryBackoff(maxRetryBackoff);
            return this;
        }

        Builder closeTimeout(@Nullable Duration closeTimeout) {
            options.closeTimeout(closeTimeout);
            return this;
        }

        TestLogConfiguration build() {
            return new TestLogConfiguration(application, host, environment, options.build());
        }

    }

}
